-- 5. Automation (Triggers)
-- --------------------------------------------------------
CREATE OR REPLACE FUNCTION handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER users_updated_at BEFORE UPDATE ON public.users FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();
CREATE TRIGGER profiles_updated_at BEFORE UPDATE ON public.profiles FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();
CREATE TRIGGER properties_updated_at BEFORE UPDATE ON public.properties FOR EACH ROW EXECUTE PROCEDURE handle_updated_at();

-- 6. Security (RLS Policies)
-- --------------------------------------------------------

-- Enable RLS
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.leads ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.properties ENABLE ROW LEVEL SECURITY;

-- Users: Only self
CREATE POLICY "Users can see their own auth data" ON public.users
    FOR SELECT USING (id = auth.uid());

-- Profiles: Publicly viewable, editable by owner
CREATE POLICY "Profiles are viewable by everyone" ON public.profiles
    FOR SELECT USING (true);

CREATE POLICY "Users can update their own profile" ON public.profiles
    FOR UPDATE USING (id = auth.uid());

-- Leads: Public can insert, only admins/agents can view
CREATE POLICY "Public leads can be created" ON public.leads
    FOR INSERT WITH CHECK (true);

CREATE POLICY "Admins and Agents can view leads" ON public.leads
    FOR SELECT USING (true); -- Placeholder: In practice, use a function to check role

-- Properties: Public can view active, admins can manage
CREATE POLICY "Public can view active properties" ON public.properties
    FOR SELECT USING (status = 'active');
